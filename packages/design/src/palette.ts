/**
 * Палитра. Построена вокруг фирменного красного Opera — #FF1B2D.
 *
 * ПРАВИЛО, которое определяет всю систему:
 * **красный — семантика, а не украшение.**
 *
 * В приложении для наблюдения за безопасностью красный обязан что-то значить.
 * Если красить им кнопки «Сохранить», он перестанет читаться как сигнал, и
 * настоящая критическая строка в таймлайне потеряется среди декора.
 *
 * Поэтому Opera Red появляется ровно в трёх местах:
 *   1. знак продукта (лого, активный индикатор навигации);
 *   2. кольцо фокуса;
 *   3. критические состояния — атака прошла, цепочка аудита сломана,
 *      сработал mandatory deny.
 *
 * Основное действие («Запустить», «Одобрить») красится инверсным нейтральным,
 * а не брендовым красным. См. `semantic.ts`.
 */

