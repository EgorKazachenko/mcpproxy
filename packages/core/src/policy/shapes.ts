import type { LockDiff } from '@mcpproxy/contracts';

/**
 * Формы и предикаты политики, **не требующие `node:crypto`**.
 *
 * Живут отдельно от `lock-check.ts` не ради красоты: производство вердикта зовёт
 * `verifyLockEntries`, то есть тянет `node:crypto`, а рендер диффа и формы апрува — нет.
 * Держи предикат рядом с производителем — и чистый вход `@mcpproxy/core/pure` затащил бы
 * криптографию в бандл рендерера через один-единственный импорт.
 */

/**
 * Код `LoadedLock.unreadable`, означающий превышение предела размера. Отличим от отказа
 * доступа: у оператора это разные истории, и лечатся они противоположным.
 */
export const SIZE_LIMIT_CODE = 'ERR_SIZE_LIMIT';

/**
 * Дифф пуст во всех четырёх слотах.
 *
 * Общий для `checkLock` и рендера намеренно. Держи каждый собственную копию условия — и
 * расхождение двух определений «пустоты» показало бы человеку текст про подделку там, где есть
 * обычный дифф, или наоборот.
 */
export const isEmptyDiff = (diff: LockDiff): boolean =>
  diff.defaults === null && diff.added.length === 0 && diff.removed.length === 0 && diff.changed.length === 0;
