/**
 * Энтропийный детектор — вторая половина R7, поверх regex-правил.
 *
 * Он ловит то, у чего нет формы: свежий формат токена, самодельный ключ, base64-блоб.
 * Regex ловит то, у чего форма есть. Ни один из двух не заменяет другой.
 *
 * **Почему детектор один, а не два.** Разведка (`04-research-findings.md` §10) описывает
 * TruffleHog, считающий энтропию для base64 **и** hex. Hex-половина здесь выкинута по
 * замеру, а не по вкусу: 32-символьный ключ Twilio даёт p50 3.62, 40-символьный git sha —
 * 3.70, обычный путь из лога — 3.61. Это одно распределение; порога, который разделил бы
 * секрет и sha, не существует, а порог 3.0 вырезал бы каждый sha в выводе `run_tests` —
 * и редакцию выключили бы в первый же день. Hex-секреты берёт regex по префиксу формата
 * (`SK` + 32 hex). Сырые числа — в `spec.md`, «Проверенные факты».
 */

/** Идентификатор для `Redaction.rule` и плейсхолдера. Публичен, как и имена regex-правил. */
export const ENTROPY_RULE_ID = 'high-entropy-base64';

/**
 * Порог. Замер на 500 случайных токенах по 32 байта: min 4.41, p1 4.55, p50 4.85; самый
 * высокий реальный ран, найденный в репозитории (`normalizeManifestForLockEntry`) — 4.09.
 * Зазор 4.09 → 4.41.
 */
export const BASE64_ENTROPY_THRESHOLD = 4.5;

/**
 * Минимальная длина рана — **выведена из порога, а не выбрана**.
 *
 * Энтропия строки длины `n` не может превысить `log2(n)`: это достигается, когда все
 * символы различны. Значит при пороге 4.5 ран короче `ceil(2^4.5) = 23` не проходит его
 * НИКОГДА, чем бы он ни был. Константа, выставленная руками ниже этого числа (у нас
 * сначала стояло 20), описывала бы границу, которой не существует, — и первый же тест на
 * «ран ровно минимальной длины проверяется» оказался бы невыполнимым.
 *
 * **Честная граница детектора, замер на 3000 токенов при пороге 4.5:**
 *
 * | длина рана | 23 | 24 | 28 | 32 | 40 | 43 | 48 |
 * |---|---|---|---|---|---|---|---|
 * | доля пойманных | 1.1 % | 4.9 % | 29 % | 72 % | 98.4 % | 99.7 % | 100 % |
 *
 * То есть это детектор ДЛИННЫХ токенов, и ниже ~28 символов он не работает по существу.
 * Короткие форматы держит regex — у них есть характерный префикс, и он там для того же.
 * Записано в `spec.md` как ограничение, а не выдаётся за покрытие.
 */
export const BASE64_MIN_RUN = Math.ceil(2 ** BASE64_ENTROPY_THRESHOLD);

export interface EntropySpan {
  readonly start: number;
  readonly end: number;
}

/**
 * Алфавит base64 вместе с base64url: `-` и `_` — url-вариант.
 *
 * **`=` в класс не входит, хотя это законный паддинг.** С ним `AWS_KEY=<токен>` становится
 * ОДНИМ раном, и плейсхолдер съедает имя переменной вместе со значением — то есть читатель
 * лога теряет ровно ту половину, которая не секрет и по которой он понимает, что произошло.
 * Цена решения — осиротевший `=` после замены и ран короче на один-два символа; на пороге
 * это не сказывается, потому что паддинг энтропию только занижает.
 *
 * Единственное место в модуле редакции, где стоит нативный `RegExp`, а не RE2, и это не
 * дыра в R6: один символьный класс с `+` не содержит ни альтернации, ни вложенной
 * квантификации, то есть бэктрекать здесь нечему — время линейно от длины входа при любом
 * входе. R6 запрещает нативный движок для **правил**, чьи паттерны приходят из внешнего
 * набора и меняются при каждом обновлении; эта строка не оттуда и не меняется.
 */
const BASE64_RUN = /[A-Za-z0-9+/_-]+/gu;

/**
 * Энтропия Шеннона в битах на символ.
 *
 * Считается по **кодовым точкам** (`for…of`), а не по кодовым единицам UTF-16: суррогатная
 * пара иначе выглядит как два разных символа и завышает энтропию строки из эмодзи.
 *
 * Пустая строка даёт ровно `0`, а не `NaN`. Разница не косметическая: `NaN >= threshold`
 * равно `false`, поэтому один `NaN` не роняет детектор, а молча его выключает.
 */
export function shannonEntropy(text: string): number {
  const frequency = new Map<string, number>();
  let length = 0;
  for (const character of text) {
    frequency.set(character, (frequency.get(character) ?? 0) + 1);
    length += 1;
  }
  if (length === 0) return 0;

  let entropy = 0;
  for (const count of frequency.values()) {
    const probability = count / length;
    entropy -= probability * Math.log2(probability);
  }
  return entropy;
}

/**
 * Раны base64-алфавита длиной ≥ `BASE64_MIN_RUN`, чья энтропия ≥ `BASE64_ENTROPY_THRESHOLD`.
 *
 * Возвращаются в порядке появления и не пересекаются: движок `g`-регулярки идёт слева
 * направо, а на этом порядке строится замена в `engine.ts`.
 */
export function findHighEntropyRuns(text: string): readonly EntropySpan[] {
  const spans: EntropySpan[] = [];
  // Свежий экземпляр на вызов: `lastIndex` у `g`-регулярки — состояние, и общий на модуль
  // объект давал бы разный результат на одном и том же входе в зависимости от предыдущего
  // вызова. Здесь это означало бы пропущенный секрет через раз.
  const scanner = new RegExp(BASE64_RUN.source, BASE64_RUN.flags);

  for (let match = scanner.exec(text); match !== null; match = scanner.exec(text)) {
    const run = match[0];
    if (run.length < BASE64_MIN_RUN) continue;
    if (shannonEntropy(run) < BASE64_ENTROPY_THRESHOLD) continue;
    spans.push({ start: match.index, end: match.index + run.length });
  }

  return spans;
}
