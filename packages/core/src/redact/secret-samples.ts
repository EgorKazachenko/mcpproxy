/**
 * Сборка тестовых фикстур, имеющих ФОРМУ секрета.
 *
 * **Почему из частей, а не литералами.** Этот эпик — детектор секретов, поэтому его корпус
 * обязан содержать строки формы настоящих креденшлов. Литералы такой формы поднимают
 * сканеры секретов (GitGuardian на PR нашёл восемь), и это не ложняк сканера, а наша
 * проблема: красная проверка на каждом пуше становится шумом, а шум — это то, за чем
 * настоящая утечка через полгода проедет незамеченной.
 *
 * **Почему не исключением путей в конфиге сканера.** Шаблон вида «все файлы `.test.ts`»
 * в списке игнора ослепляет
 * сканер на тестах — а тесты типовое место, куда настоящий ключ попадает по недосмотру.
 * Проект, чей тезис в том, что защита должна быть структурной, не имеет права лечить это
 * отключением проверки. Здесь строки формы секретов просто не существуют на диске: они
 * возникают в памяти на время прогона.
 *
 * **Что удерживает корректность.** Ничего в этом файле не проверяется напрямую — и не нужно:
 * сборщик, разошедшийся с паттерном, красит соответствующий тест «правило ловит свою форму»
 * в `rules.test.ts`, а их там по одному на каждое правило набора плюс тест, требующий, чтобы
 * покрыты были ВСЕ правила. Сломать сборщик молча нельзя.
 *
 * Значения детерминированы: прогон обязан быть воспроизводимым, а случайная фикстура
 * превращает красный тест в лотерею.
 */

const cycle = (alphabet: string, length: number): string =>
  alphabet.repeat(Math.ceil(length / alphabet.length)).slice(0, length);

/** `[A-Za-z0-9]` — самый частый класс в паттернах набора. */
export const alnum = (length: number): string => cycle('A1b2C3d4E5f6G7h8I9j0K1l2M3n4O5p6Q7r8S9t0', length);

/** `[A-Z0-9]` — AWS-идентификаторы. */
export const upper = (length: number): string => cycle('AB1CD2EF3GH4IJ5KL6MN7OP8QR9ST0UVWXYZ2345', length);

/** `[0-9a-f]` — Twilio SID и всё, что притворяется хэшем. */
export const hex = (length: number): string => cycle('0123456789abcdef', length);

/** `[0-9]` — числовые сегменты токенов Slack. */
export const digits = (length: number): string => cycle('1234567890', length);

/**
 * Строка из РАЗЛИЧНЫХ символов: энтропия равна ровно `log2(length)`, то есть максимальна для
 * своей длины. Нужна энтропийному детектору, где важно не «похоже на секрет», а измеримое
 * значение: `distinct(42)` даёт 5.39, и это то же число, что стояло в прежнем литерале.
 */
export const distinct = (length: number): string =>
  'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789'.slice(0, length);

/** Заголовок PEM. Собирается из слов: целиком он и есть то, что ловит правило. */
export const pemHeader = (kind: string): string => ['-----BEGIN', kind, 'PRIVATE', 'KEY-----'].join(' ');

/** Пароль внутри URL. Не слово из словаря — иначе тест читается как настоящая утечка. */
export const password = (): string => `pw${alnum(11)}`;

/**
 * `@` отдельной константой — чтобы форма `://пользователь:пароль@хост` не складывалась даже
 * в ИСХОДНИКЕ этого файла. Иначе сканер (и наш собственный детектор) поднимает шаблон, в
 * котором подстановка ещё не выполнена, и мы возвращаемся ровно к тому, от чего уходим.
 */
const AT = '@';

export const dbUri = (): string => `postgresql://svc:${password()}${AT}db.internal:5432/app`;

export const basicAuthUrl = (): string => `https://deploy:${password()}${AT}registry.internal/`;
