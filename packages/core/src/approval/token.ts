import type { ApprovalRequest } from '@mcpproxy/contracts';

/**
 * Правило выбора опасного токена — потребитель поля `ApprovalRequest.argvFromParams`,
 * которого до E5 не существовало (`R41`, `R63`, расписка в `WORK.md`).
 *
 * `R41` велит человеку **набрать** токен из самой команды, чтобы разрешить вызов; вставка в
 * окне отключена. Смысл требования — заставить прочитать то, чем управляет модель, а не то,
 * что написал автор рецепта. Поэтому правило обязано быть **вычислимым из того, что окно
 * получило**, а не угаданным по эвристике «что тут выглядит опасным»: эвристика по виду
 * строки промахивается ровно на подготовленном входе.
 *
 * **Правило: первый по порядку элемент `argv`, подставленный из параметров и непустой.**
 * Первый, а не самый длинный и не последний: порядок argv следует порядку объявления
 * параметров в манифесте (`R19`), то есть он стабилен между вызовами и виден человеку в том
 * же тексте, на который он смотрит. Правило «самый длинный» меняло бы требуемый токен от
 * значения к значению и обучало бы кликать, не читая.
 */

export interface DangerousToken {
  /** Индекс в `argv` той же формы — того самого массива, который показали человеку. */
  readonly index: number;
  readonly token: string;
  /**
   * `false` — модель не подставила в команду ни одного непустого элемента, и токен взят из
   * хвоста argv. Окно обязано различать эти случаи: во втором подтверждение всё ещё требует
   * прочитать команду, но обещания «вы набрали то, чем управляет модель» уже не несёт.
   */
  readonly fromParams: boolean;
}

/**
 * Индексы, годные к употреблению: целые, в диапазоне, без повторов, указывающие на непустой
 * элемент. Инвариант объявлен в контракте, но проверяется здесь, а не принимается на веру:
 * форма приезжает из другого процесса, и выход за диапазон дал бы `undefined` в качестве
 * токена, то есть окно, которое невозможно подтвердить.
 */
function usable(request: ApprovalRequest): number[] {
  const seen = new Set<number>();
  const indices: number[] = [];
  for (const index of request.argvFromParams ?? []) {
    if (!Number.isInteger(index) || index < 0 || index >= request.argv.length) continue;
    if (seen.has(index)) continue;
    seen.add(index);
    if ((request.argv[index] ?? '') === '') continue;
    indices.push(index);
  }
  return indices.sort((a, b) => a - b);
}

/**
 * `null` — только у формы, в которой непусто нечего набирать вовсе: пустой `argv`. Это не
 * «токен не требуется»: окно, не сумевшее выбрать токен, обязано отказать, а не разрешить
 * без набора (`R44` — отсутствие подтверждения есть отказ).
 */
export function dangerousToken(request: ApprovalRequest): DangerousToken | null {
  const indices = usable(request);
  const first = indices[0];
  if (first !== undefined) {
    return { index: first, token: request.argv[first] as string, fromParams: true };
  }

  // Хвост, а не `argv[0]`: нулевой элемент — путь к бинарю, он одинаков у всех вызовов
  // рецепта, и набор его не заставляет прочитать ничего про этот конкретный вызов.
  for (let index = request.argv.length - 1; index >= 0; index -= 1) {
    const value = request.argv[index] ?? '';
    if (value !== '') return { index, token: value, fromParams: false };
  }
  return null;
}
