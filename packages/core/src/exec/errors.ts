import type { RecipeName } from '@mcpproxy/contracts';
import type { CommandId } from './sandbox.js';


/**
 * Отказы E3 — отдельным модулем, а не рядом с интерфейсом.
 *
 * Иначе получается цикл: `netpolicy.ts` бросает отказ политики, `sandbox.ts` знает про
 * режимы, режимы знают про `netpolicy.ts`. Тип отказа не зависит ни от чего в этом графе,
 * поэтому и живёт в его основании.
 */

/**
 * Код отказа E3. Дискриминант, а не текст сообщения.
 *
 * Существует потому, что `Verdict` (`domain.ts:9`) знает четыре значения, и E4 обязан
 * выбрать одно по тому, что бросил E3. Без кода единственным дискриминатором остаётся
 * строка сообщения — и безопасным умолчанием становится `verdict: 'error'`, то есть **вызов,
 * заблокированный политикой, попадает в лог как сбой прокси**. D6 говорит ровно обратное:
 * отказ политики — штатный исход решения, а не отказ сервиса.
 *
 * `poisoned` и `group-not-drained` разведены намеренно: первый означает «демон больше не
 * выдаёт вызовов, нужно вмешательство», второй — «вмешательство понадобилось из-за ЭТОГО
 * вызова». Оператору это разные новости.
 */
export type ExecErrorCode =
  /** Режим не поддержан: `container` вовсе или `seatbelt` вне macOS (R2, R3). */
  | 'mode-unsupported'
  /** Шаблон домена не прошёл перепроверку перед принуждением (R13). Отказ политики. */
  | 'invalid-domain'
  /** `run()` у освобождённой песочницы (R50). */
  | 'disposed'
  /** Демон отравлен предыдущим вызовом и новых не выдаёт (R52). */
  | 'poisoned'
  /** Пустота группы процессов ЭТОГО вызова не подтверждена (R52). */
  | 'group-not-drained'
  /** Прокси или трастовый бандл CA не подняты — baseline был бы слепым (R31). */
  | 'proxy-down'
  /** `allowedDomains: ["*"]` не доехал до srt: вендор начал валидировать (R54). */
  | 'wildcard-dropped'
  /** Ребёнка не удалось запустить: нет бинаря, нет оболочки. */
  | 'spawn-failed'
  /** Синглтон srt ещё не инициализирован. */
  | 'srt-uninitialized';

/**
 * Что именно отказало. Поля необязательные, потому что не в каждой точке отказа известны
 * все три: `assertModeSupported` вызывается до всякого рецепта.
 */
export interface ExecErrorContext {
  readonly recipeName?: RecipeName;
  readonly commandId?: CommandId;
  /** Pid лидера группы, если отказ про группу процессов. Оператору его и искать. */
  readonly pid?: number;
  /** Подтверждена ли пустота группы на момент отказа. */
  readonly groupDrained?: boolean;
}

/**
 * Единственный класс отказа E3.
 *
 * Экспортируется наружу пакета (`exec/index.ts`), иначе `instanceof` у E4 невозможен, и
 * различать отказ политики от сбоя пришлось бы сравнением текста — ровно та связь, которую
 * заморозка поверхности должна убирать.
 */
export class ExecError extends Error {
  readonly code: ExecErrorCode;
  readonly context: ExecErrorContext;

  constructor(code: ExecErrorCode, message: string, context: ExecErrorContext = {}) {
    super(message);
    this.name = 'ExecError';
    this.code = code;
    this.context = context;
  }
}
