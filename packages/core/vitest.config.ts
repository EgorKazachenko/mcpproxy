import { defineConfig } from 'vitest/config';

// `include` один и покрывает весь `src` — по той же причине, что и в `contracts`: тест,
// положенный мимо шаблона, исчезает молча. Что шаблон и правда покрывает всё, что лежит на
// диске, утверждают `src/coverage.test.ts` (E6) и `src/policy/runner.test.ts` (E1) — первый
// сверяет список файлов с шаблоном, второй закрепляет сам шаблон.
export default defineConfig({
  test: {
    environment: 'node',
    include: ['src/**/*.test.ts'],
    // Поднято против дефолтных 5 с ради E3: интеграционные наборы поднимают настоящий
    // seatbelt, ходят в сеть через прокси srt и ждут таймаутов дочерних процессов.
    testTimeout: 60_000,
    hookTimeout: 60_000,
    // Наборы E3, поднимающие синглтон srt, делят один глобальный прокси и один стор
    // нарушений на процесс. Параллельные воркеры дали бы каждому свой процесс — но
    // `updateConfig` под семафором R21 несёт гарантию атрибуции только внутри процесса, и
    // два форка одновременно держали бы два прокси на одной машине. Один поток — не вкус.
    fileParallelism: false,
  },
});
