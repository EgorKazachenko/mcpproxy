import { defineConfig } from 'vitest/config';

// Форма — из `packages/contracts/vitest.config.ts`: один `include`, покрывающий весь `src`.
// Тест, положенный мимо шаблона, исчезает молча; соответствие «всё, что лежит на диске,
// попадает под include» проверяет `src/exec/runner.test.ts`.
//
// `testTimeout` поднят против дефолтных 5 с: интеграционные наборы E3 поднимают настоящий
// seatbelt, ходят в сеть через прокси srt и ждут таймаутов дочерних процессов.
export default defineConfig({
  test: {
    environment: 'node',
    include: ['src/**/*.test.ts'],
    testTimeout: 60_000,
    hookTimeout: 60_000,
    // Наборы, поднимающие синглтон srt, делят один глобальный прокси и один стор нарушений
    // на процесс. Параллельные воркеры дали бы каждому свой процесс — но `updateConfig`
    // под семафором R21 несёт гарантию атрибуции только внутри процесса, и два форка
    // одновременно держали бы два прокси на одной машине. Один поток — не вкус, а R21.
    fileParallelism: false,
  },
});
