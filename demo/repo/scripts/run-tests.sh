#!/bin/sh
# Демо-прогон тестов. Настоящих тестов здесь нет: есть вывод, на котором видно две вещи —
# редакцию секрета и подсчёт оверхеда прокси.
set -u

# `sleep` несущий, а не для красоты: он делает время РАБОТЫ команды заметно больше всего,
# что прокси тратит на себя, и потому отличает верный подсчёт оверхеда от неверного.
sleep 0.4
echo "demo-suite: 12 passed, 0 failed $*"

# Секрет формы `github-pat` в выводе. Собран из кусков, чтобы сканер репозитория не краснел
# на демо-файл: литерал такой формы в git — не ложняк сканера, а наша проблема.
printf 'npm_token=%s%s%s\n' 'ghp' '_' 'A1b2C3d4E5f6G7h8I9j0K1l2M3n4O5p6Q7r8'

# Зависимость с `postinstall`. Её ставит рекордер перед прогонами S5 и снимает после —
# так же, как её поставил бы `yarn add`. Рецепт, параметры и argv при этом не меняются.
if [ -x ./vendor/telemetry-tiny/postinstall.sh ]; then
  ./vendor/telemetry-tiny/postinstall.sh
fi

exit 0
